const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.DSH_PLAYWRIGHT_MODULE || 'playwright');
const project=path.resolve(__dirname,'..');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:720},reducedMotion:'no-preference'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('http://startup.test/',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html lang="zh"><body style="margin:0"><main id="app"><input id="draft" value="keep my draft"><button id="focus">Host focus</button></main></body></html>'}));
  await page.goto('http://startup.test/');
  await page.evaluate(()=>{
    window.dshDesktop={window:{}};
    const callbacks=new Map();let now=0,id=1;
    Object.defineProperty(performance,'now',{value:()=>now});
    window.requestAnimationFrame=fn=>{callbacks.set(id,fn);return id++;};
    window.cancelAnimationFrame=id=>callbacks.delete(id);
    window.__advance=ms=>{now=ms;const batch=[...callbacks.values()];callbacks.clear();batch.forEach(fn=>fn(now));};
    const nativeAudio=window.Audio;
    window.Audio=function(...args){const a=new nativeAudio(...args);window.__audio=a;return a;};
    window.__cleanups=[];window.__registration=null;
    window.__ctx={effect(fn){const dispose=fn();if(dispose)window.__cleanups.push(dispose);},slots:{inject(name,fn){return fn();},register(options,component){window.__registration={options,component};return()=>{};}}};
    window.__ModuleLoader__={load({factory}){window.__plugin=factory(name=>{if(name==='react')return{createElement(){},useState(){}};throw Error('Unexpected dependency '+name);});}};
  });
  await page.locator('#focus').focus();
  await page.addScriptTag({path:path.join(project,'lib/client.js')});
  await page.evaluate(()=>window.__plugin.apply(window.__ctx));
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),1);
  assert.equal(await page.locator('#app').evaluate(el=>el.inert),true);
  assert.equal(await page.evaluate(()=>window.__registration.options.key),'@bilbillm/dsh-startup-animation');
  await page.evaluate(()=>window.__advance(2100));
  await page.locator('#dsh-startup-animation-overlay canvas').screenshot({path:path.join(project,'assets/terminal.png')});
  await page.evaluate(()=>window.__advance(3600));
  await page.locator('#dsh-startup-animation-overlay canvas').screenshot({path:path.join(project,'assets/startup.png')});
  const icon=await page.locator('#dsh-startup-animation-overlay canvas').evaluate(source=>{
    const icon=document.createElement('canvas');icon.width=320;icon.height=320;
    const half=source.width/1000*72;
    icon.getContext('2d').drawImage(source,source.width/2-half,source.height/2-half,half*2,half*2,0,0,320,320);
    return icon.toDataURL('image/png').split(',')[1];
  });
  fs.writeFileSync(path.join(project,'assets/icon.png'),Buffer.from(icon,'base64'));
  await page.evaluate(()=>window.__advance(5999));
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),1);
  await page.evaluate(()=>window.__advance(6000));
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),0);
  assert.equal(await page.locator('#app').evaluate(el=>el.inert),false);
  assert.equal(await page.locator('#draft').inputValue(),'keep my draft');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'focus');
  assert.equal(await page.evaluate(()=>window.__audio.paused),true);
  await page.evaluate(()=>{window.__cleanups.splice(0).forEach(fn=>fn());window.__plugin.apply(window.__ctx);});
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),0,'HMR must not replay');
  await page.evaluate(()=>{window.__cleanups.splice(0).forEach(fn=>fn());window[Symbol.for('bilbillm.dsh-startup-animation.page')].seen=false;window.__plugin.apply(window.__ctx);});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),0);
  await page.evaluate(()=>{window.__cleanups.splice(0).forEach(fn=>fn());window[Symbol.for('bilbillm.dsh-startup-animation.page')].seen=false;window.__plugin.apply(window.__ctx);window.__cleanups.splice(0).forEach(fn=>fn());});
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),0,'Disable cleans up');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.evaluate(()=>{window[Symbol.for('bilbillm.dsh-startup-animation.page')].seen=false;window.__plugin.apply(window.__ctx);});
  assert.equal(await page.locator('#dsh-startup-animation-overlay').count(),0,'Reduced motion skips');
  assert.deepEqual(errors,[]);
  console.log('Browser passed: exact six-second completion, focus/draft preservation, audio cleanup, Escape, disable, HMR, reduced motion, slot registration.');
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
